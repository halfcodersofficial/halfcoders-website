export default function CategoryIcon({
    name,
    className,
}: {
    name: string | null;
    className?: string;
}) {
    const Icon = (name && ICONS[name as keyof typeof ICONS]) || Shapes;
    return <Icon className={cn("size-5", className)} aria-hidden />;
}
